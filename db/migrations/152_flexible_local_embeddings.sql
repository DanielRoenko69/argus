-- Built-in Knowledge and Agent Memory must accept local as well as cloud
-- embedding dimensions. Untyped halfvec keeps storage compact and preserves
-- exact cosine search. Dimension-specific ANN indexes can be added per corpus
-- later; a single HNSW index cannot safely mix dimensions.

DROP INDEX IF EXISTS idx_kb_chunks_embedding_hnsw;
ALTER TABLE mcp_kb_chunks
  ALTER COLUMN embedding TYPE halfvec
  USING embedding::halfvec;

DROP INDEX IF EXISTS idx_agent_memory_embedding_hnsw;
ALTER TABLE mcp_agent_memory
  ALTER COLUMN embedding TYPE halfvec
  USING embedding::halfvec;

COMMENT ON COLUMN mcp_kb_chunks.embedding IS
  'Provider-neutral local/cloud embeddings; all chunks in one RAG index must use the configured model dimension.';
COMMENT ON COLUMN mcp_agent_memory.embedding IS
  'Provider-neutral local/cloud embeddings generated by EMBEDDING_MODEL.';
